"""Generate the committed SYNTHETIC DEMO dataset (public/data/demo/).

Everything here is simulated with a fixed random seed. It exists so the app works
out of the box and in a public repository without redistributing licensed data.
It is NOT market data and must never be presented as such: every file carries
datasetKind "demo", verification level "synthetic", and a name that says so.

Design choices that keep it obviously synthetic:
  * the demo index starts at 100.00 on 1990-01-02 (unlike any real index level)
  * the series ends on 2025-12-31 (fixed; it never looks "current")
"""
from __future__ import annotations

import math
import random
import sys
from datetime import date

from common import PUBLIC_DATA, SCHEMA_VERSION, series_filename, trading_days, write_json

SEED = 20240611
OUT = PUBLIC_DATA / "demo"
START, END = date(1990, 1, 2), date(2025, 12, 31)
BUILT_AT = "2025-12-31T23:00:00Z"  # fixed so the committed demo files are reproducible
SYNTH_NOTE = "SYNTHETIC DEMO SERIES generated by pipeline/make_demo.py (seed %d). Not market data." % SEED


def simulate_index(rng: random.Random, n: int):
    """Regime-switching returns with volatility clustering and occasional crash clusters."""
    closes, vols = [100.0], [0.009]
    regime, var = 0, 0.009 ** 2
    for _ in range(1, n):
        if regime == 0 and rng.random() < 0.0025:
            regime = 1  # stress regime
        elif regime == 1 and rng.random() < 0.05:
            regime = 0
        drift = 0.0005 if regime == 0 else -0.0015
        shock = rng.gauss(0, 1)
        var = 0.000002 + 0.08 * (var * shock * shock) + 0.9 * var
        var = min(max(var, 0.0045 ** 2), 0.05 ** 2)
        vol = math.sqrt(var) * (1.0 if regime == 0 else 1.8)
        r = drift + vol * shock
        if regime == 1 and rng.random() < 0.02:
            r -= abs(rng.gauss(0.03, 0.015))  # crash day
        closes.append(max(closes[-1] * math.exp(r), 1.0))
        vols.append(vol)
    return closes, vols


def simulate_vix(rng: random.Random, closes: list[float], vols: list[float]) -> list[float]:
    out, level = [], 18.0
    for i, v in enumerate(vols):
        r = 0.0 if i == 0 else math.log(closes[i] / closes[i - 1])
        target = 3.5 + v * math.sqrt(252) * 100 * 0.9 + (-r * 400 if r < 0 else -r * 80)
        level = level + 0.25 * (target - level) + rng.gauss(0, 0.6)
        out.append(round(min(max(level, 9.0), 85.0), 2))
    return out


def simulate_stock(rng: random.Random, index: list[float], beta: float, idio: float, drift: float, start_price: float):
    out = [start_price]
    for i in range(1, len(index)):
        m = math.log(index[i] / index[i - 1])
        r = drift + beta * m + rng.gauss(0, idio)
        out.append(max(out[-1] * math.exp(r), 0.5))
    return out


def series_doc(symbol: str, name: str, asset_class: str, dates: list[str], closes: list[float]) -> dict:
    return {
        "schemaVersion": SCHEMA_VERSION,
        "symbol": symbol,
        "name": name,
        "assetClass": asset_class,
        "tradable": asset_class in ("etf", "stock"),
        "currency": "USD",
        "fields": ["date", "close", "adjClose"],
        "priceNotes": "Synthetic values. adjClose equals close (no dividends simulated).",
        "source": {
            "provider": "WOI demo generator (synthetic)",
            "url": "pipeline/make_demo.py",
            "retrievedAt": BUILT_AT,
            "license": "Synthetic data created for this project. Free to use; carries no market information.",
            "method": SYNTH_NOTE,
            "marketTimezone": "America/New_York",
        },
        "verification": {"level": "synthetic", "detail": SYNTH_NOTE, "crossCheck": None},
        "rows": [[d, round(c, 2), round(c, 2)] for d, c in zip(dates, closes)],
    }


def main() -> int:
    rng = random.Random(SEED)
    days = [d.isoformat() for d in trading_days(START, END)]
    idx, vols = simulate_index(rng, len(days))
    vix = simulate_vix(rng, idx, vols)
    specs = [
        ("DEMO-INDEX", "Demo Index (synthetic stand-in for the S&P 500)", "core_index", "index", None),
        ("DEMO-VIX", "Demo Volatility Index (synthetic stand-in for VIX)", "core_vol", "volatility_index", None),
        ("SPY", "SPY - synthetic demo series (not SPY market data)", "watchlist", "etf", (1.0, 0.0015, 0.00025, 212.5)),
        ("QQQ", "QQQ - synthetic demo series (not QQQ market data)", "watchlist", "etf", (1.2, 0.006, 0.0003, 168.2)),
        ("NVDA", "NVDA - synthetic demo series (not NVDA market data)", "watchlist", "stock", (1.7, 0.024, 0.0004, 96.4)),
        ("TSLA", "TSLA - synthetic demo series (not TSLA market data)", "watchlist", "stock", (1.9, 0.03, 0.0003, 87.3)),
        ("GOOGL", "GOOGL - synthetic demo series (not GOOGL market data)", "watchlist", "stock", (1.1, 0.016, 0.0003, 71.8)),
    ]
    manifest_series = []
    for sym, name, role, ac, params in specs:
        if sym == "DEMO-INDEX":
            closes = idx
        elif sym == "DEMO-VIX":
            closes = vix
        else:
            beta, idio, target_drift, end_price = params
            raw = simulate_stock(rng, idx, beta, idio, 0.0, 100.0)
            # Replace the path's average daily log return with a modest target drift (keeps the
            # day-to-day volatility and index correlation), then scale to a modest final level.
            logs = [math.log(raw[i] / raw[i - 1]) for i in range(1, len(raw))]
            mean = sum(logs) / len(logs)
            path = [1.0]
            for r in logs:
                path.append(path[-1] * math.exp(r - mean + target_drift))
            closes = [c * end_price / path[-1] for c in path]
        doc = series_doc(sym, name, ac, days, closes)
        fname = series_filename(sym)
        digest = write_json(OUT / "series" / fname, doc)
        manifest_series.append({
            "symbol": sym, "name": name, "role": role, "assetClass": ac, "file": f"series/{fname}",
            "rows": len(days), "firstDate": days[0], "lastDate": days[-1], "sha256": digest, "verificationLevel": "synthetic",
        })
    manifest = {
        "schemaVersion": SCHEMA_VERSION,
        "datasetKind": "demo",
        "label": "DEMO - synthetic data, not market data",
        "builtAt": BUILT_AT,
        "lastMarketDate": days[-1],
        "isLive": False,
        "core": {"index": "DEMO-INDEX", "vol": "DEMO-VIX"},
        "series": manifest_series,
        "validation": {"errors": [], "warnings": [], "fetchFailures": {}},
        "crossChecks": {},
        "notes": [SYNTH_NOTE, "Run `npm run data:update` to build the real, source-backed dataset on your own computer."],
    }
    write_json(OUT / "manifest.json", manifest)
    print(f"Wrote demo dataset: {len(manifest_series)} series x {len(days)} sessions ({days[0]} -> {days[-1]}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
