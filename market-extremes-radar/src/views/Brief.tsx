import { useMemo, useState } from "react";
import { Button, Card, Notice } from "../components/ui";
import { generateBrief } from "../lib/brief";
import { downloadText } from "../lib/storage";
import { watchRow, RS_BENCHMARK } from "../lib/watchlist";
import { useData } from "../state";

function renderInline(s: string) {
  return s.split(/(\*\*[^*]+\*\*)/g).map((part, k) => (part.startsWith("**") ? <strong key={k} className="text-paper">{part.slice(2, -2)}</strong> : <span key={k}>{part}</span>));
}

export default function Brief() {
  const { analytics, dataset, watchlist } = useData();
  const [copied, setCopied] = useState<string | null>(null);
  const brief = useMemo(() => {
    const ds = dataset!;
    const bench = ds.watchlist[RS_BENCHMARK] ?? null;
    const watch = watchlist.map((s) => watchRow(s, ds.watchlist[s] ?? null, bench));
    return generateBrief({ frame: analytics!.frame, dataset: ds, events: analytics!.events, watch, generatedAt: new Date().toISOString() });
  }, [analytics, dataset, watchlist]);

  const copy = async (text: string, what: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(what);
    } catch {
      setCopied("Clipboard blocked by the browser - use Download instead.");
    }
    setTimeout(() => setCopied(null), 2500);
  };

  return (
    <div className="space-y-4">
      {dataset!.kind === "demo" && <Notice tone="risk">This brief is built from the synthetic DEMO dataset. Do not publish it.</Notice>}
      <Card
        title="Weekly research brief"
        subtitle="Generated by fixed rules from the data on this screen. No AI model, no paid service."
        right={
          <div className="flex flex-wrap justify-end gap-2">
            <Button variant="primary" onClick={() => copy(brief.markdown, "Markdown copied")}>Copy Markdown</Button>
            <Button onClick={() => copy(brief.text, "Plain text copied")}>Copy plain text</Button>
            <Button onClick={() => downloadText(`woi-brief-${brief.asOf}.md`, brief.markdown, "text/markdown")}>Download .md</Button>
          </div>
        }
      >
        {copied && <p className="mb-3 text-xs text-gain" role="status">{copied}</p>}
        <article className="max-w-3xl">
          <h1 className="font-serif text-2xl text-paper">{brief.title}</h1>
          {brief.sections.map((s) => (
            <section key={s.heading} className="mt-6">
              <h2 className="border-b border-line pb-1 text-[13px] font-semibold uppercase tracking-[0.12em] text-gold">{s.heading}</h2>
              <ul className="mt-2 space-y-1.5 text-sm leading-relaxed text-paper/85">
                {s.bullets.map((b, k) => (
                  <li key={k} className="flex gap-2"><span className="text-muted" aria-hidden>–</span><span>{renderInline(b)}</span></li>
                ))}
              </ul>
            </section>
          ))}
          <footer className="mt-6 space-y-1 border-t border-line pt-3 text-xs italic text-muted">
            {brief.footer.map((x) => <p key={x}>{x}</p>)}
          </footer>
        </article>
      </Card>
      <Card title="How the brief is built">
        <ul className="list-disc space-y-1 pl-5 text-xs leading-relaxed text-muted">
          <li>“This week” is the last 5 sessions. Changes compare the latest close with the close 5 sessions earlier.</li>
          <li>New historical matches: trigger onsets in the last 5 sessions, compared with earlier events of the same trigger (20-session cluster rule).</li>
          <li>A signal “failed” when its realised 20-session return had the opposite sign to the median 20-session return of earlier events known at the signal date (minimum 5 earlier events). Signals from the last 120 sessions are checked.</li>
          <li>Research questions are templates chosen by the current rule-based condition, VIX level, trend and watchlist laggards.</li>
        </ul>
      </Card>
    </div>
  );
}
